#!/usr/bin/env python3
"""Builds the Rust crate notice file for @resvg/resvg-wasm. Run by gen-resvg-notices.sh in a Rust container.

usage: gen-resvg-notices.py <workdir> <output.md> <resvg-js tag>
"""
import hashlib
import os
import re
import sys
import tomllib

work, out, tag = sys.argv[1], sys.argv[2], sys.argv[3]
vendor = os.path.join(work, "vendor")
LICENSE_RE = re.compile(r"^(licen[sc]e|copying|unlicense|notice)([-_.].*)?$", re.I)
COPYRIGHT_RE = re.compile(r"^\s*(?:Copyright|\(c\)|©)\b.*", re.I)

crates = []
for line in open(os.path.join(work, "crates.txt"), encoding="utf8"):
    line = line.strip()
    if not line:
        continue
    pkg, lic, repo = (line.split("|") + ["", ""])[:3]
    m = re.match(r"^(\S+) v(\S+)(?: \((.*)\))?$", pkg)
    if not m:
        raise SystemExit(f"unparseable cargo tree line: {line}")
    name, version, src = m.group(1), m.group(2), m.group(3) or ""
    if name == "resvg-js":
        continue  # the root package (the JS binding itself) is not part of the notices
    crates.append({"name": name, "version": version, "license": lic, "repo": repo, "src": src})
crates.sort(key=lambda c: (c["name"], c["version"]))

problems = []
groups = {}  # text hash -> {"text": str, "crates": [...]}
for c in crates:
    d = os.path.join(vendor, f"{c['name']}-{c['version']}")
    if not os.path.isdir(d):
        d = os.path.join(vendor, c["name"])
    if not os.path.isdir(d):
        problems.append(f"{c['name']} {c['version']}: not vendored")
        continue
    meta = tomllib.load(open(os.path.join(d, "Cargo.toml"), "rb"))["package"]
    c["authors"] = [a for a in meta.get("authors", []) if isinstance(a, str)]
    c["repo"] = (meta.get("repository") or c["repo"] or "").removesuffix(".git").rstrip("/")
    c["license"] = c["license"] or meta.get("license") or meta.get("license-file", "")
    files = sorted(f for f in os.listdir(d) if LICENSE_RE.match(f) and os.path.isfile(os.path.join(d, f)))
    texts = [open(os.path.join(d, f), encoding="utf8", errors="replace").read().replace("\r\n", "\n").strip() for f in files]
    texts = [t for t in texts if t]
    fallback = False
    if not texts:
        # No license file in the crate: use the standard SPDX text with the Cargo.toml authors as holders.
        spdx = next((i for i in ("MIT", "BSD-3-Clause", "Apache-2.0") if i in re.split(r"[ /()]+", c["license"])), None)
        who = ", ".join(a.split("<")[0].strip() for a in c["authors"]) or f"the {c['name']} contributors ({c['repo']})"
        if not spdx or not (c["authors"] or c["repo"]):
            problems.append(f"{c['name']} {c['version']}: ships no license file and none can be derived (license {c['license']!r})")
            continue
        tpl = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "licenses", spdx + ".txt"), encoding="utf8").read()
        texts = [tpl.replace("{{copyright}}", who).strip()]
        fallback = True
    holders = []
    for t in texts:
        for ln in t.split("\n"):
            if COPYRIGHT_RE.match(ln) and ln.strip() not in holders:
                holders.append(ln.strip())
    c["fallback"] = fallback
    c["holders"] = holders or [f"Copyright (c) {', '.join(c['authors'])}" if c["authors"] else ""]
    for t in texts:
        h = hashlib.sha256(re.sub(r"(?im)^\s*(copyright|\(c\)).*$", "", t).encode()).hexdigest()
        g = groups.setdefault(h, {"text": t, "crates": []})
        if c not in g["crates"]:
            g["crates"].append(c)
if problems:
    raise SystemExit("cannot generate Rust crate notices:\n  " + "\n  ".join(problems))

lines = [
    f"Statically linked Rust crates in `@resvg/resvg-wasm` 2.6.2 (`index_bg.wasm`, built from resvg-js {tag})",
    "",
    "Generated by `packages/cli/scripts/gen-resvg-notices.sh` (do not edit). resvg-js publishes no Cargo.lock, so",
    f"the set was resolved from the resvg-js {tag} Cargo.toml (with its [patch] forks) for",
    "`wasm32-unknown-unknown`, normal dependencies only; the resolved lock is `resvg-wasm-Cargo.lock` next to this",
    "file. Each license text below is the text the crate itself ships; crates are grouped by identical text, with",
    "each crate's copyright lines.",
    "",
    f"{len(crates)} crates:",
    "",
]
for c in crates:
    lines.append(f"- {c['name']} {c['version']} ({c['license']})" + (f" - {c['repo']}" if c["repo"] else ""))
lines.append("")
for h in sorted(groups, key=lambda k: (groups[k]["crates"][0]["name"], k)):
    g = groups[h]
    lines += ["----", "", "Applies to: " + ", ".join(f"{c['name']} {c['version']}" for c in g["crates"]), ""]
    for c in g["crates"]:
        for hl in c["holders"]:
            if hl:
                lines.append(f"- {c['name']}: {hl}" + (" (standard text: the crate ships no license file)" if c["fallback"] else ""))
    lines += ["", "~~~~text", g["text"], "~~~~", ""]
open(out, "w", encoding="utf8").write("\n".join(lines).rstrip() + "\n")
print(f"wrote {out}: {len(crates)} crates, {len(groups)} distinct license texts")
