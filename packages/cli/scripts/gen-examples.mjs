// Embeds examples/*.cosmo.json and examples/templates/*.cosmo.json into src/examples.gen.ts so
// `pcosmo examples` and `pcosmo init --template` work from the single-file plugin bundle.
// Usage: node packages/cli/scripts/gen-examples.mjs [--check]
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath, URL } from "node:url";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const out = fileURLToPath(new URL("../src/examples.gen.ts", import.meta.url));

function collect(dir) {
  return readdirSync(root + dir)
    .filter((f) => f.endsWith(".cosmo.json"))
    .sort()
    .map((f) => {
      const json = readFileSync(`${root}${dir}/${f}`, "utf8");
      const meta = JSON.parse(json).meta ?? {};
      return {
        name: f.replace(/\.cosmo\.json$/, ""),
        title: String(meta.title ?? ""),
        description: String(meta.description ?? ""),
        json,
      };
    });
}

const lit = (v) => JSON.stringify(v);
const list = (items) =>
  `[\n${items
    .map(
      (i) =>
        `  { name: ${lit(i.name)}, title: ${lit(i.title)}, description: ${lit(i.description)}, json: ${lit(i.json)} },`,
    )
    .join("\n")}\n]`;

const text = `// Generated by packages/cli/scripts/gen-examples.mjs from /examples. Do not edit.
export interface EmbeddedSpec {
  readonly name: string;
  readonly title: string;
  readonly description: string;
  /** The spec file text, verbatim. */
  readonly json: string;
}

export const examples: readonly EmbeddedSpec[] = ${list(collect("examples"))};

export const templates: readonly EmbeddedSpec[] = ${list(collect("examples/templates"))};
`;

if (process.argv.includes("--check")) {
  let cur = "";
  try {
    cur = readFileSync(out, "utf8");
  } catch {
    /* missing */
  }
  if (cur !== text) {
    console.error("examples.gen.ts is stale. Run: scripts/pc run gen:examples");
    process.exit(1);
  }
} else {
  writeFileSync(out, text);
}
