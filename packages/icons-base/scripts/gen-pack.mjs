// Dev-time generator: embeds `<pkg>/icons.json` + `<pkg>/svg/*.svg` into `<pkg>/src/pack.gen.ts`.
// Usage (in a container): node packages/icons-base/scripts/gen-pack.mjs packages/icons-lucide
// Deterministic: sorted keys, light whitespace minification only (sanitizing happens at runtime).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { minify } from "./minify.mjs";

const dir = process.argv[2];
if (!dir) throw new Error("usage: gen-pack.mjs <package dir>");
const manifest = JSON.parse(readFileSync(join(dir, "icons.json"), "utf8"));

const files = {};
for (const icon of [...manifest.icons].sort((a, b) => (a.file < b.file ? -1 : 1))) {
  files[icon.file] = minify(readFileSync(join(dir, icon.file), "utf8"));
}
manifest.icons.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));

const ts = `// GENERATED by packages/icons-base/scripts/gen-pack.mjs from icons.json + svg/. Do not edit.
import type { LoadedIconPack } from "@platformcosmo/core";

export const pack: LoadedIconPack = {
  manifest: ${JSON.stringify(manifest, null, 2).replace(/\n/g, "\n  ")},
  files: ${JSON.stringify(files, null, 2).replace(/\n/g, "\n  ")},
};
`;
mkdirSync(join(dir, "src"), { recursive: true });
writeFileSync(join(dir, "src/pack.gen.ts"), ts);
const total = Object.values(files).reduce((n, s) => n + s.length, 0);
console.log(`${dir}: ${manifest.icons.length} icons, ${total} bytes embedded`);
